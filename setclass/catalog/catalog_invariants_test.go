func sliceToBitmask(s []int) uint64 {
	var mask uint64
	for _, pc := range s {
		mask |= 1 << uint(pc)
	}
	return mask
}

func TestForteClass_All224_CSVReferenceAndInvariants(t *testing.T) {
	t.Parallel()

	rows := parseForteCatalogCSV(t)
	all := catalog.ForteClasses()
	require.Len(t, all, 224)

	totalOrbitNonEmpty := 0
	totalOrbitAll := 0
	diffCount := 0
	symmetricCount := 0
	chiralCount := 0

	validTnSym := map[int]bool{1: true, 2: true, 3: true, 4: true, 6: true, 12: true}
	validInSym := map[int]bool{0: true, 1: true, 2: true, 3: true, 4: true, 6: true, 12: true}

	for idx, row := range rows {
		t.Run(row.Forte, func(t *testing.T) {
			t.Parallel()

			fc := all[idx]
			require.True(t, fc.IsValid())
			assert.Equal(t, row.Forte, fc.String())
			assert.Equal(t, row.Cardinality, fc.Cardinality())
			assert.Equal(t, row.Ordinal, fc.Ordinal())
			assert.Equal(t, row.IsZ, fc.IsZ())

			// Prime forms and masks (Rahn & Forte)
			pfRahn := fc.PrimeForm()
			pfForte := fc.FortePrimeForm()
			require.NotNil(t, pfRahn)
			require.NotNil(t, pfForte)
			assert.Equal(t, row.PrimeRahn, pfRahn)
			assert.Equal(t, row.PrimeForte, pfForte)
			assert.Equal(t, row.RahnMask, fc.PrimeMask())
			assert.Equal(t, row.ForteMask, fc.FortePrimeMask())
			assert.Equal(t, row.ForteDiffers, fc.RahnForteDiffer())
			assert.Equal(t, fc.PrimeMask() != fc.FortePrimeMask(), fc.RahnForteDiffer())

			pfRahnWith, err := fc.PrimeFormWith(catalog.Rahn)
			require.NoError(t, err)
			assert.Equal(t, pfRahn, pfRahnWith)
			assert.Equal(t, pfRahn, fc.MustPrimeFormWith(catalog.Rahn))

			pfForteWith, err := fc.PrimeFormWith(catalog.Forte)
			require.NoError(t, err)
			assert.Equal(t, pfForte, pfForteWith)
			assert.Equal(t, pfForte, fc.MustPrimeFormWith(catalog.Forte))

			pmRahnWith, err := fc.PrimeMaskWith(catalog.Rahn)
			require.NoError(t, err)
			assert.Equal(t, row.RahnMask, pmRahnWith)
			assert.Equal(t, row.RahnMask, fc.MustPrimeMaskWith(catalog.Rahn))

			pmForteWith, err := fc.PrimeMaskWith(catalog.Forte)
			require.NoError(t, err)
			assert.Equal(t, row.ForteMask, pmForteWith)
			assert.Equal(t, row.ForteMask, fc.MustPrimeMaskWith(catalog.Forte))

			// Bitmask / slice bijection
			assert.Equal(t, row.Cardinality, len(pfRahn))
			assert.Equal(t, row.Cardinality, len(pfForte))
			assert.Equal(t, row.Cardinality, bits.OnesCount64(fc.PrimeMask()))
			assert.Equal(t, row.Cardinality, bits.OnesCount64(fc.FortePrimeMask()))
			assert.Equal(t, fc.PrimeMask(), sliceToBitmask(pfRahn))
			assert.Equal(t, fc.FortePrimeMask(), sliceToBitmask(pfForte))
			if row.Cardinality >= 1 {
				assert.Equal(t, 0, pfRahn[0])
				assert.Equal(t, 0, pfForte[0])
				assert.NotZero(t, fc.PrimeMask()&1)
				assert.NotZero(t, fc.FortePrimeMask()&1)
				for i := 1; i < len(pfRahn); i++ {
					assert.Greater(t, pfRahn[i], pfRahn[i-1])
					assert.LessOrEqual(t, pfRahn[i], 11)
				}
			}

			// Interval-class vector and handshaking lemma
			icv := fc.IntervalVector()
			icvSlice := fc.IntervalVectorSlice()
			assert.Equal(t, row.Vector, icv)
			assert.Equal(t, icv[:], icvSlice)
			sumICV := 0
			for _, v := range icv {
				sumICV += v
			}
			assert.Equal(t, row.Cardinality*(row.Cardinality-1)/2, sumICV)

			// Morris invariance vector and symmetry invariants
			iv := fc.InvarianceVector()
			ivSlice := fc.InvarianceVectorSlice()
			assert.Equal(t, row.MorrisIV, iv)
			assert.Equal(t, iv[:], ivSlice)

			assert.Equal(t, row.TInvariance, fc.TnSymmetry())
			assert.Equal(t, row.IInvariance, fc.InSymmetry())
			assert.True(t, validTnSym[fc.TnSymmetry()])
			assert.True(t, validInSym[fc.InSymmetry()])
			assert.Equal(t, fc.TnSymmetry(), iv[0])
			assert.Equal(t, fc.InSymmetry(), iv[1])
			assert.Equal(t, row.TInvariance+row.IInvariance, fc.DegreeOfSymmetry())

			wantOrbit := 1
			if row.Cardinality > 0 {
				wantOrbit = 24 / (row.TInvariance + row.IInvariance)
			}
			assert.Equal(t, wantOrbit, fc.OrbitSize())

			wantInvSym := row.IInvariance > 0
			assert.Equal(t, wantInvSym, fc.IsInversionallySymmetric())
			assert.Equal(t, !wantInvSym, fc.IsChiral())
			assert.Equal(t, row.TnTypesCount, fc.TnTypeCount())
			if wantInvSym {
				assert.Equal(t, 1, fc.TnTypeCount())
			} else {
				assert.Equal(t, 2, fc.TnTypeCount())
			}

			// Hexachord invariance vector self-complementarity check (K-10)
			if row.Cardinality == 6 {
				if row.IsZ {
					assert.Equal(t, 0, iv[4], "Z-hexachord %s must have iv[4]==0", row.Forte)
					assert.Equal(t, 0, iv[5], "Z-hexachord %s must have iv[5]==0", row.Forte)
					assert.False(t, fc.IsSelfComplementary())
				} else {
					assert.True(t, iv[4] > 0 || iv[5] > 0, "non-Z hexachord %s must have iv[4]>0 or iv[5]>0", row.Forte)
					assert.True(t, fc.IsSelfComplementary())
				}
			}

			// MinSpan
			assert.Equal(t, row.MinSpan, fc.MinSpan())
			if row.Cardinality == 0 {
				assert.Equal(t, 0, fc.MinSpan())
			} else {
				assert.Equal(t, pfRahn[len(pfRahn)-1], fc.MinSpan())
			}
		})

		fc := all[idx]
		totalOrbitAll += fc.OrbitSize()
		if row.Cardinality >= 1 {
			totalOrbitNonEmpty += fc.OrbitSize()
		}
		if fc.RahnForteDiffer() {
			diffCount++
		}
		if fc.IsInversionallySymmetric() {
			symmetricCount++
		} else {
			chiralCount++
		}
	}

	assert.Equal(t, 4095, totalOrbitNonEmpty, "sum of non-empty ForteClass orbits must be 4095")
	assert.Equal(t, 4096, totalOrbitAll, "sum of all 224 ForteClass orbits must be 4096")
	assert.Equal(t, 6, diffCount, "exact 6 ForteClasses differ between Rahn and Forte")
	assert.Equal(t, 96, symmetricCount, "exact 96 achiral ForteClasses")
	assert.Equal(t, 128, chiralCount, "exact 128 chiral ForteClasses")
}

