func parsePrimeFormDigits(t testing.TB, s string) []int {
	t.Helper()
	if s == "" {
		return []int{}
	}
	out := make([]int, 0, len(s))
	for i := 0; i < len(s); i++ {
		ch := s[i]
		switch {
		case ch >= '0' && ch <= '9':
			out = append(out, int(ch-'0'))
		case ch == 'T':
			out = append(out, 10)
		case ch == 'E':
			out = append(out, 11)
		default:
			t.Fatalf("unexpected prime form digit %q in %q", ch, s)
		}
	}
	return out
}

func parseIntArray6(t testing.TB, s string) [6]int {
	t.Helper()
	parts := strings.Split(s, ",")
	require.Len(t, parts, 6)
	var out [6]int
	for i, p := range parts {
		v, err := strconv.Atoi(strings.TrimSpace(p))
		require.NoError(t, err)
		out[i] = v
	}
	return out
}

