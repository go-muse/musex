func parseForteCatalogCSV(t testing.TB) []forteCatalogRow {
	t.Helper()
	r := csv.NewReader(strings.NewReader(strings.TrimSpace(forteCatalogCSV)))
	records, err := r.ReadAll()
	require.NoError(t, err)
	require.Len(t, records, 225) // 1 header + 224 rows

	rows := make([]forteCatalogRow, 0, 224)
	for _, rec := range records[1:] {
		c, err := strconv.Atoi(rec[1])
		require.NoError(t, err)
		ord, err := strconv.Atoi(rec[2])
		require.NoError(t, err)
		rahnMask, err := strconv.ParseUint(rec[7], 10, 64)
		require.NoError(t, err)
		forteMask, err := strconv.ParseUint(rec[8], 10, 64)
		require.NoError(t, err)
		tnTypesCount, err := strconv.Atoi(rec[12])
		require.NoError(t, err)
		tInv, err := strconv.Atoi(rec[13])
		require.NoError(t, err)
		iInv, err := strconv.Atoi(rec[14])
		require.NoError(t, err)
		minSpan, err := strconv.Atoi(rec[17])
		require.NoError(t, err)

		carter := 0
		hasCarter := false
		if rec[18] != "" {
			carter, err = strconv.Atoi(rec[18])
			require.NoError(t, err)
			hasCarter = true
		}

		rows = append(rows, forteCatalogRow{
			Forte:        rec[0],
			Cardinality:  c,
			Ordinal:      ord,
			IsZ:          rec[3] == "Z",
			PrimeRahn:    parsePrimeFormDigits(t, rec[4]),
			PrimeForte:   parsePrimeFormDigits(t, rec[5]),
			ForteDiffers: rec[6] == "yes",
			RahnMask:     rahnMask,
			ForteMask:    forteMask,
			Vector:       parseIntArray6(t, rec[9]),
			ZPartner:     rec[10],
			Complement:   rec[11],
			TnTypesCount: tnTypesCount,
			TInvariance:  tInv,
			IInvariance:  iInv,
			M5Image:      rec[15],
			MorrisIV:     parseIntArray8(t, rec[16]),
			MinSpan:      minSpan,
			Carter:       carter,
			HasCarter:    hasCarter,
		})
	}
	return rows
}

