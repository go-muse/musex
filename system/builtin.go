// Builtins returns all built-in systems in catalog order: Traditional,
// HeptatonicSecondGenerated8, Blackwood15, UpsAndDowns15, Porcupine15,
// Blackwood17, QuarterTones17, Positions19, UpsAndDowns22, QuarterTones22,
// Porcupine22, QuarterTones24, SharpsAndFlats31, Fokker31,
// ExtendedPythagorean41, UpsAndDowns41, ExtendedPythagorean53, UpsAndDowns53,
// ArelEzgiUzdilek53 and ManeriSims72. New built-in systems may take their
// places in the catalog, including between existing ones; only the relative
// order of the existing systems is kept, not their positions.
func Builtins() iter.Seq[*System] {
	return func(yield func(*System) bool) {
		for _, s := range builtins {
			if !yield(s) {
				return
			}
		}
	}
}

// LookupBuiltin returns the built-in system with exactly the name name (case
// sensitive, without normalization) and true, or nil and false.
func LookupBuiltin(name string) (*System, bool) {
	for _, s := range builtins {
		if s.name == name {
			return s, true
		}
	}

	return nil, false
}

// builtin returns a built-in system with the boundary letter C.
func builtin(name string, n int, offsets [letter.Count]int, c int, rule *Rule) *System {
	return MustNew(Definition{
		Name:        name,
		Classes:     n,
		Boundary:    letter.C,
		Offsets:     offsets,
		Chromatic:   c,
		Alterations: rule,
	})
}
